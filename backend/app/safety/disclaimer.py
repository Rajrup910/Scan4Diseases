"""Fixed safety text, owned by the application.

Master specification, section 27: the mandatory warning must be implemented in the
application itself and must not depend on the LLM producing it. Every string in this file
is a constant. None of it is generated, and none of it passes through the language model
on its way to the user -- including the Hindi versions, which are translated here once
rather than at request time.

That last point matters. If the LLM translated the disclaimer per request, an unlucky
sample could soften "this is not a medical diagnosis" into something weaker, and nobody
would notice.
"""


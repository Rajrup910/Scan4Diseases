def get_disclaimer(language: Language = Language.ENGLISH) -> str:
    return DISCLAIMERS.get(language, DISCLAIMERS[Language.ENGLISH])


def outcome_name(outcome: Outcome, language: Language = Language.ENGLISH) -> str:
    return OUTCOME_NAMES[outcome].get(language, OUTCOME_NAMES[outcome][Language.ENGLISH])


def outcome_advice(outcome: Outcome, language: Language = Language.ENGLISH) -> str:
    return OUTCOME_ADVICE[outcome].get(language, OUTCOME_ADVICE[outcome][Language.ENGLISH])


def triage_label(category: TriageCategory, language: Language = Language.ENGLISH) -> str:
    return TRIAGE_LABELS[category].get(language, TRIAGE_LABELS[category][Language.ENGLISH])


def triage_advice(category: TriageCategory, language: Language = Language.ENGLISH) -> str:
    return TRIAGE_ADVICE[category].get(language, TRIAGE_ADVICE[category][Language.ENGLISH])


def confidence_phrasing(
    confidence: float, class_name: str, language: Language = Language.ENGLISH
) -> str:
    template = CONFIDENCE_PHRASING.get(language, CONFIDENCE_PHRASING[Language.ENGLISH])
    return template.format(percent=round(confidence * 100), name=class_name)


def low_confidence_notice(language: Language = Language.ENGLISH) -> str:
    return LOW_CONFIDENCE_NOTICE.get(language, LOW_CONFIDENCE_NOTICE[Language.ENGLISH])


def quality_rejection_message(language: Language = Language.ENGLISH) -> str:
    return QUALITY_REJECTION.get(language, QUALITY_REJECTION[Language.ENGLISH])


def llm_unavailable_notice(language: Language = Language.ENGLISH) -> str:
    return LLM_UNAVAILABLE_NOTICE.get(language, LLM_UNAVAILABLE_NOTICE[Language.ENGLISH])



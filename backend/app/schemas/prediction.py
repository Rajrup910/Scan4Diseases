"""Response schema for POST /predict."""

from __future__ import annotations

from pydantic import BaseModel, ConfigDict, Field

from backend.app.schemas.common import Language, Outcome, TriageCategory
from backend.app.schemas.questionnaire import Questionnaire


class ClassProbability(BaseModel):
    code: str = Field(examples=["mel"])
    name: str = Field(description="Display name in the requested language.")
    probability: float = Field(ge=0.0, le=1.0)
    malignancy: str = Field(examples=["malignant", "premalignant", "benign"])


class ImageQuality(BaseModel):
    """Result of the pre-classification quality gate."""

    acceptable: bool
    blur_score: float = Field(description="Variance of the Laplacian. Lower means blurrier.")
    brightness: float = Field(ge=0.0, le=255.0, description="Mean luminance.")
    width: int
    height: int
    warnings: list[str] = Field(default_factory=list)


class TriageResult(BaseModel):
    """Output of the deterministic safety layer.

    Produced entirely by rules in `services/triage.py`. The LLM is given this object and
    asked to explain it; it cannot change `category`.
    """

    category: TriageCategory
    label: str = Field(description="Human-readable category name in the requested language.")
    advice: str = Field(description="Fixed, non-generated guidance text for this category.")
    reasons: list[str] = Field(
        default_factory=list,
        description="Which rules fired, in plain language. Shown to the user and logged.",
    )
    rule_ids: list[str] = Field(
        default_factory=list,
        description="Stable identifiers of the rules that fired, for auditing and tests.",
    )
    low_confidence: bool = Field(
        description="True when the model's top score is below the configured threshold."
    )


class PredictionResponse(BaseModel):
    model_config = ConfigDict(protected_namespaces=())

    request_id: str
    language: Language

    outcome: Outcome = Field(
        default=Outcome.LESION,
        description=(
            "What the front-stage router decided the photo is. `lesion` carries a full "
            "disease result; `healthy` and `other_damage` short-circuit it and the disease "
            "fields below are placeholders (empty `probabilities`, no Grad-CAM). Clients "
            "should branch on this."
        ),
    )
    router_probabilities: dict[str, float] | None = Field(
        default=None,
        description="Router category probabilities (lesion/healthy/other_damage/not_skin), "
        "when the router ran. For transparency and debugging.",
    )

    predicted_class: str = Field(examples=["mel"])
    predicted_name: str = Field(description="Display name in the requested language.")
    confidence: float = Field(
        ge=0.0,
        le=1.0,
        description=(
            "The model's highest softmax score. This is NOT the probability that the user "
            "has this condition, and must never be presented to a user as one."
        ),
    )
    probabilities: list[ClassProbability]

    image_quality: ImageQuality
    gradcam_url: str | None = Field(
        default=None, description="Path to the Grad-CAM overlay. Temporary; deleted after the TTL."
    )
    gradcam_focus: str | None = Field(
        default=None, description="Plain-language description of where the heatmap concentrated."
    )

    triage: TriageResult
    questionnaire: Questionnaire

    explanation: str | None = Field(
        default=None, description="LLM-written plain-language explanation. Null if the LLM is unavailable."
    )
    explanation_available: bool = Field(
        description="False when the LLM could not be reached; the rest of the result is still valid."
    )

    disclaimer: str = Field(
        description=(
            "Mandatory medical disclaimer, generated by the application itself and never by "
            "the LLM. Clients must display it with every result."
        )
    )

    model_arch: str | None = None
    stub: bool = Field(
        default=False,
        description="True when no trained checkpoint was loaded and the values are placeholders.",
    )
    inference_ms: float | None = None
